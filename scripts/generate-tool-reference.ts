/**
 * Writes docs/tool-reference.md from the real tool definitions, so the
 * reference cannot drift from what agents actually see. Run: pnpm docs:tools
 * (test/docs.test.ts fails if the committed file is stale).
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { z } from 'zod';

import { CxCallerClient } from '../src/client.js';
import { loadConfig, TOOLSETS } from '../src/config.js';
import type { AnyToolSpec } from '../src/tools/define.js';
import { allTools } from '../src/tools/index.js';

type Schema = {
  type?: string | string[];
  format?: string;
  enum?: unknown[];
  const?: unknown;
  anyOf?: Schema[];
  items?: Schema;
  properties?: Record<string, Schema>;
  required?: string[];
  description?: string;
  minimum?: number;
  maximum?: number;
  additionalProperties?: unknown;
};

function typeOf(schema: Schema): string {
  if (schema.anyOf) {
    const parts = schema.anyOf.map(typeOf).filter((part) => part !== 'null');
    const nullable = schema.anyOf.some((part) => part.type === 'null');

    return [...parts, ...(nullable ? ['null'] : [])].join(' \\| ');
  }

  if (schema.enum) {
    return schema.enum.map((value) => `\`${JSON.stringify(value)}\``).join(' \\| ');
  }

  if (schema.type === 'array') {
    const item = schema.items ? typeOf(schema.items) : 'any';

    return `array of ${item}`;
  }

  if (schema.type === 'object') {
    if (schema.properties) {
      return `object {${Object.keys(schema.properties).join(', ')}}`;
    }

    return 'object';
  }

  if (schema.type === 'null') {
    return 'null';
  }

  const base = Array.isArray(schema.type) ? schema.type.join(' \\| ') : (schema.type ?? 'any');
  const extras = [schema.format, schema.minimum !== undefined ? `min ${schema.minimum}` : undefined, schema.maximum !== undefined ? `max ${schema.maximum}` : undefined].filter(Boolean);

  return extras.length > 0 ? `${base} (${extras.join(', ')})` : base;
}

function cell(text: string): string {
  return text.replace(/\|/g, '\\|').replace(/\n+/g, ' ').trim();
}

function paramRows(schema: Schema, prefix = ''): string[] {
  const required = new Set(schema.required ?? []);
  const rows: string[] = [];

  for (const [name, property] of Object.entries(schema.properties ?? {})) {
    rows.push(`| \`${prefix}${name}\` | ${typeOf(property)} | ${required.has(name) ? 'yes' : ''} | ${cell(property.description ?? '')} |`);

    // One level into object and array-of-object parameters, so nested fields are documented too.
    const nested = property.type === 'array' ? property.items : property;

    if (nested?.type === 'object' && nested.properties) {
      rows.push(...paramRows(nested, `${prefix}${name}${property.type === 'array' ? '[]' : ''}.`));
    }
  }

  return rows;
}

function badges(spec: AnyToolSpec): string {
  const tags: string[] = [];

  if (!spec.mutating) {
    tags.push('read-only');
  } else {
    tags.push('changes data');
  }

  if (spec.reachesPeople) {
    tags.push('can place calls');
  }

  if (spec.destructive) {
    tags.push('destructive');
  }

  return tags.map((tag) => `\`${tag}\``).join(' ');
}

export function buildToolReference(): string {
  const config = loadConfig({});
  const specs = allTools({ client: new CxCallerClient({ apiKey: 'x', baseUrl: 'http://localhost' }), config });
  const titles: Record<string, string> = {
    account: 'Account and reference',
    contacts: 'Contacts',
    campaigns: 'Campaigns',
    calls: 'Calls',
    analytics: 'Analytics',
  };
  const lines: string[] = [
    '# Tool reference',
    '',
    '<!-- GENERATED by `pnpm docs:tools` from the tool definitions. Do not edit by hand. -->',
    '',
    `Every tool the CXCaller MCP server exposes (${specs.length} in all), with its parameters exactly as an agent sees them. For how to use them together, see the [usage guide](./usage-guide.md).`,
    '',
    'Conventions: arguments are `snake_case`; ids are UUIDs; phone numbers are E.164 (`+94771234567`). **Required** parameters are marked; everything else is optional. A parameter typed `… \\| null` accepts `null` to clear a value, whereas leaving it out leaves the value unchanged.',
    '',
    'Tags: `read-only` never changes anything · `changes data` writes · `can place calls` may cause a real phone to ring · `destructive` deletes or cannot be undone.',
    '',
  ];

  for (const toolset of TOOLSETS) {
    const inSet = specs.filter((spec) => spec.toolset === toolset);

    lines.push(`## ${titles[toolset]}`, '');

    for (const spec of inSet) {
      const schema = z.toJSONSchema(z.object(spec.inputSchema)) as Schema;
      const rows = paramRows(schema);

      lines.push(`### \`${spec.name}\``, '', badges(spec), '', spec.description, '');

      if (rows.length > 0) {
        lines.push('| Parameter | Type | Required | Description |', '| --- | --- | --- | --- |', ...rows, '');
      } else {
        lines.push('_No parameters._', '');
      }
    }
  }

  return `${lines.join('\n').trimEnd()}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = new URL('../docs/tool-reference.md', import.meta.url);

  writeFileSync(target, buildToolReference());
  console.log(`wrote ${fileURLToPath(target)}`);
}
